'use strict';
const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),ctx={};vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root,'film-core.js'),'utf8')+'\nthis.Film = RinkFilmCore;',ctx);
const f=ctx.Film;
assert.equal(f.labelTime(68),'1:08');
assert.equal(f.labelTime(-1),'0:00');
assert.equal(f.samplingTimes(0,1,6).length,0,'very short clips cannot be sampled');
const times=f.samplingTimes(1,31,6);assert.equal(times.length,6);assert(times[0]>=1&&times.at(-1)<=31);
const base64='data:image/jpeg;base64,'+Buffer.from('example').toString('base64');
const good={playerId:'8478402',playerName:'Connor McDavid',season:'20262027',identifier:'EDM #97',consent:true,frames:times.map(time=>({time,image:base64}))};
assert.equal(f.validSelection(good),true);
assert.equal(f.validSelection({...good,consent:false}),false,'consent is mandatory');
assert.equal(f.validSelection({...good,frames:[good.frames[0]]}),false,'at least two frames');
assert.equal(f.validSelection({...good,frames:[{time:1,image:'http://evil.example/puck.jpg'},good.frames[0]]}),false,'no remote URLs');
assert.equal(f.validSelection({...good,frames:times.map(time=>({time,image:base64})).concat(times.map(time=>({time,image:base64})))}),false,'frame limit');
assert.equal(f.validSelection({...good,identifier:''}),false,'jersey/team identity cue required');
const assessment={identityConfirmed:false,summary:'Uncertain',findings:[{trait:'skating',score:5,confidence:'high',explanation:'Speed',evidence:[{time:times[0],observation:'Skater in left wing position'}]}]};
let x=f.scrubAnalysis(assessment,times);assert.equal(x.findings[0].score,null,'unverified identity must not receive a score');
const single={identityConfirmed:true,findings:[{trait:'iq',score:5,confidence:'high',evidence:[{time:times[0],observation:'One still cannot prove hockey IQ'}]}]};
assert.equal(f.scrubAnalysis(single,times).findings[0].score,null,'one-frame score must be withheld');
const bogus={identityConfirmed:true,summary:'',findings:[{trait:'iq',score:4,confidence:'high',evidence:[{time:999,observation:'Made a pass'}]}]};
assert.equal(f.scrubAnalysis(bogus,times).findings.length,0,'timestamp fabrication rejected');
const low={identityConfirmed:true,summary:'',findings:[{trait:'puck',score:5,confidence:'low',evidence:[{time:times[0],observation:'Puck near skater'}]}]};
assert.equal(f.scrubAnalysis(low,times).findings[0].score,null,'low-confidence scores hidden');
console.log('Film validation, sampling and safety tests passed.');
