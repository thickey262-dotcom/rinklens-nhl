'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const players=[];
for(let i=0;i<25;i++)players.push({id:'C'+i,name:'C '+i,pos:'C',gp:8,p:8+i,toi:16,advanced:{gp:8,xgfPct:30+i,cfPct:30+i,ffPct:30+i,ixG60:i/15,hdCfPct:30+i}});
for(let i=0;i<25;i++)players.push({id:'D'+i,name:'D '+i,pos:'D',gp:8,p:1+i,toi:20,advanced:{gp:8,xgfPct:20+i,cfPct:20+i,ffPct:20+i,ixG60:i/15,hdCfPct:20+i}});
const ctx={S:{players,source:'nhl'},RinkAdvanced:{read:(p,key)=>p.advanced?.[key]??null},esc:x=>String(x).replaceAll('<','&lt;').replaceAll('>','&gt;')};
vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT,'reportcards.js'),'utf8')+'\nthis.RinkReports=RinkReports;',ctx);
vm.runInContext(fs.readFileSync(path.join(ROOT,'autoscout.js'),'utf8')+'\nthis.RinkAuto=RinkAuto;',ctx);
const score=ctx.RinkAuto.estimate;
assert(score(players[24]).score>score(players[0]).score,'higher same-position metrics improve proxy');
assert.equal(score(players[24]).covered,6);
assert.equal(score(players[24]).ranks[0].rank.count,25,'same position peers only');
assert.equal(score({...players[10],advanced:{...players[10].advanced,gp:1}}),null,'short samples withheld');
assert.equal(score({...players[10],advanced:{...players[10].advanced,xgfPct:null}}),null,'required metric missing');
assert(score({...players[10],advanced:{...players[10].advanced,hdCfPct:null,cfPct:null}}),'missing optional metrics can renormalize');
ctx.S.source='demo';assert.equal(score(players[24]),null,'fictional data never yields proxy');ctx.S.source='nhl';
const h=ctx.RinkAuto.panel(players[12]);assert(h.includes('NOT AN EYE TEST')&&h.includes('MoneyPuck')&&h.includes('How was this calculated?'),'clear source and limitations');
assert(ctx.RinkAuto.explanation(score(players[24])).includes('not') || ctx.RinkAuto.explanation(score(players[24])).includes('Neither'));
ctx.RinkAuto.invalidate(); assert(score(players[24]),'cache invalidation works');
console.log('Auto Scout sample-size, peer, data coverage, labeling and cache tests passed.');
