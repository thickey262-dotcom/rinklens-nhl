'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),path=require('node:path');
const store={},listeners={};
const classes=()=>{const set=new Set();return {contains:x=>set.has(x),toggle:(x,force)=>{if(force===undefined?(!set.has(x)):force)set.add(x);else set.delete(x);return set.has(x)}}};
const btn=()=>({attributes:{},listeners:{},textContent:'',setAttribute(k,v){this.attributes[k]=v},addEventListener(k,cb){this.listeners[k]=cb}});
const text=btn(),advanced=btn(),table={classList:classes()},body={classList:classes()};
const nodes={textSizeToggle:text,advancedColumnsToggle:advanced,playerTable:table};
const doc={body,getElementById:id=>nodes[id],addEventListener:(name,fn)=>{listeners[name]=fn}};
const storage={getItem:k=>store[k]??null,setItem:(k,v)=>{store[k]=v}};
const ctx={document:doc,localStorage:storage,console};
vm.createContext(ctx);vm.runInContext(fs.readFileSync(path.join(__dirname,'..','easy-read.js'),'utf8'),ctx);
assert.equal(text.attributes['aria-pressed'],'false');
assert.equal(advanced.attributes['aria-pressed'],'false');
assert.equal(table.classList.contains('show-advanced'),false,'advanced columns hidden by default');
text.listeners.click();assert.equal(body.classList.contains('large-text'),true);
assert.equal(text.attributes['aria-pressed'],'true');assert.equal(store['rinklens-large-text-v1'],'true');
text.listeners.click();assert.equal(body.classList.contains('large-text'),false);
advanced.listeners.click();assert.equal(table.classList.contains('show-advanced'),true);
assert.equal(advanced.textContent,'Hide advanced stats');
advanced.listeners.click();assert.equal(table.classList.contains('show-advanced'),false);
let clicked=0,prevented=false;
listeners.keydown({key:'Enter',target:{closest:()=>({click:()=>clicked++})},preventDefault:()=>prevented=true});
assert.equal(clicked,1);assert.equal(prevented,true);
listeners.keydown({key:'Escape',target:{closest:()=>({click:()=>clicked++})},preventDefault:()=>{}});
assert.equal(clicked,1);
console.log('Readability toggles and keyboard shortcuts work.');
